def style_header(ws, row, headers, widths):
    for j, h in enumerate(headers, 1):
        c = ws.cell(row=row, column=j, value=h)
        c.font = HF; c.fill = HFILL; c.border = BORD; c.alignment = CTR
    for j, w in enumerate(widths, 1):
        ws.column_dimensions[ws.cell(row=1, column=j).column_letter].width = w


def note_block(ws, cell, text, span, height):
    ws[cell] = text; ws[cell].font = NOTE; ws[cell].alignment = WRAP
    ws.merge_cells(f"{cell}:{span}{cell[1:]}"); ws.row_dimensions[int(cell[1:])].height = height


def wavg(g, val, wt):
    g = g[g[val].notna() & g[wt].notna()]
    s = g[wt].sum()
    return (g[val] * g[wt]).sum() / s if s else np.nan


