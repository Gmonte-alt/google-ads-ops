def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--ledger", default=r"C:\Projects\google-ads-ops\commitments\microsoft_home_baseline.yaml")
    ap.add_argument("--core-workbook", required=True,
                    help="Unblended core run workbook at the baseline date")
    ap.add_argument("--assessment-workbook", required=True,
                    help="Post-adoption 84d --rpl-blend 0 assessment workbook")
    ap.add_argument("--backtest-workbook", required=True,
                    help="No-blend 5-anchor backtest comparison workbook")
    ap.add_argument("--cutover-date", default=None, help="Membership cutover date (YYYY-MM-DD)")
    ap.add_argument("--location-export", default=None,
                    help="Editor location export CSV — authoritative current campaigns for ALL states")
    ap.add_argument("--exec-out", default=None,
                    help="Also write a manager-facing workbook (campaign language only) to this path")
    ap.add_argument("--grouping", choices=["A", "B"], default="A",
                    help="A: Value=T4+T5 (150%% plan). B: Core=T3+T4, Value=T5 (140%% plan — Texas stays in Tier 2)")
    ap.add_argument("--target-roas-policy", type=float, default=TARGET_ROAS,
                    help="Return standard used for BID TARGETS only (model/ledger stay on 1.5). E.g. 1.4")
    ap.add_argument("--out", default=f"Microsoft_Home_ReTier_Rollout_Plan_{dt.date.today():%Y-%m-%d}.xlsx")
    a = ap.parse_args(argv)
    global GROUPS
    GROUPS = GROUPING_PLANS[a.grouping]

    cutover = a.cutover_date or "(set --cutover-date)"
    ledger_new, ledger_old, meta = load_ledger(a.ledger)
    camp_df, econ, state_to_shell = load_assessment(a.assessment_workbook)
    tw = load_trajectory(a.backtest_workbook)

    loc_map = load_location_export(a.location_export) if a.location_export else None
    df = assemble(ledger_new, ledger_old, camp_df, econ, state_to_shell, tw, loc_map)
    groups_df = group_rollup(df, camp_df, a.target_roas_policy)
    build(df, groups_df, meta, camp_df, a.out, cutover)

    if a.exec_out:
        schedule = build_step_schedule(groups_df, cutover)
        write_exec_workbook(a.exec_out, df, groups_df, schedule, meta, cutover,
                            a.target_roas_policy)
        print(f"wrote {a.exec_out} (manager-facing)")
    print(f"wrote {a.out}  [grouping {a.grouping}, targets @ {a.target_roas_policy*100:.0f}% ROAS]")
    print(f"  {len(df)} committed states | {int(df['moving'].sum())} changing campaigns | "
          f"{int(df['membership_unknown'].sum())} verify via location export | "
          f"{int(df['needs_targeting_add'].sum())} true additions | "
          f"{int(df['sub_threshold'].sum())} sub-threshold")
    for _, g in groups_df.iterrows():
        mv = f"{g['move_pct']*100:+.0f}%" if pd.notna(g["move_pct"]) else "n/a"
        print(f"  {g['group']:22s} target ${g['target_tcpa']:6.2f}  vs current "
              f"${g['current_tcpa'] if pd.notna(g['current_tcpa']) else 0:6.2f}  ({mv})  "
              f"{g['conv_day']:.1f} conv/day  {g['std_verdict']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
