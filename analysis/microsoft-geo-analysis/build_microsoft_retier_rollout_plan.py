def assemble(ledger_new, ledger_old, camp_df, econ, state_to_shell, tw,
             loc_map=None):
    if loc_map:
        # Location export is authoritative and complete — overrides the
        # model's eligible-only primary-spend inference for every state.
        state_to_shell = {**state_to_shell, **loc_map}
    rows = []
    for state, tier in ledger_new.items():
        e = econ.loc[state] if state in econ.index else None
        grp = None
        if state in STANDALONE:
            grp = f"{state} (standalone)"
        else:
            for g, cfg in GROUPS.items():
                if tier in cfg["tiers"]:
                    grp = g
        # destination shell
        if state in STANDALONE:
            r = match_shell(camp_df, STANDALONE[state])
            dest = str(r["campaign_name"]) if r is not None else f"({state} shell)"
        else:
            r = match_shell(camp_df, GROUPS[grp]["shell_pattern"])
            dest = str(r["campaign_name"]) if r is not None else f"({grp} shell)"
        cur_shell = state_to_shell.get(state)
        has_activity = (e is not None and pd.notna(e.get("spend")) and float(e.get("spend") or 0) > 0)
        note_val = e.get("sub_threshold_note") if e is not None else None
        sub = bool(pd.notna(note_val) and str(note_val).strip() and str(note_val).strip().lower() != "nan")
        clicks = float(e["clicks"]) if e is not None and pd.notna(e.get("clicks")) else 0.0
        conv = float(e["conversions"]) if e is not None and pd.notna(e.get("conversions")) else 0.0
        spend = float(e["spend"]) if e is not None and pd.notna(e.get("spend")) else 0.0
        rpl = float(e["rpl"]) if e is not None and pd.notna(e.get("rpl")) else np.nan
        traj = tw.loc[state] if state in tw.index else None
        cls = str(traj["classification"]) if traj is not None else ""
        slope = float(traj["rpl_slope_pct_per_week"]) if traj is not None and pd.notna(traj.get("rpl_slope_pct_per_week")) else np.nan
        r2 = float(traj["r_squared"]) if traj is not None and pd.notna(traj.get("r_squared")) else np.nan
        rows.append({
            "state": state, "new_tier": tier, "group": grp,
            "old_tier": ledger_old.get(state, "(first commitment)"),
            "current_shell": cur_shell or "(no current primary campaign)",
            "dest_shell": dest,
            "moving": int(bool(cur_shell) and cur_shell != dest),
            # Primary-campaign map only covers eligible states. Sub-threshold states
            # with spend are targeted SOMEWHERE (unresolvable from model outputs);
            # zero-activity states may genuinely need targeting added.
            "membership_unknown": int(cur_shell is None and has_activity),
            "needs_targeting_add": int(cur_shell is None and not has_activity),
            "sub_threshold": int(sub),
            "clicks": clicks, "conversions": conv, "spend": spend, "rpl": rpl,
            "ideal_tcpa": rpl / TARGET_ROAS if pd.notna(rpl) else np.nan,
            "traj_class": cls, "slope": slope, "r2": r2,
        })
    df = pd.DataFrame(rows)
    # "(first commitment)" has two distinct meanings; label them so the workbook
    # self-explains (prevents the "are we growing into new states?" misreading):
    #   earned eligibility  = state cleared the click threshold on sustained volume
    #   coverage expansion  = sub-threshold trickle state, now measured instead of invisible
    first = df["old_tier"] == "(first commitment)"
    df.loc[first & (df["sub_threshold"] == 0), "old_tier"] = "(first commitment — earned eligibility)"
    df.loc[first & (df["sub_threshold"] == 1), "old_tier"] = "(first commitment — coverage expansion)"
    df["tier_rank"] = df["new_tier"].map({t: i for i, t in enumerate(TIER_ORDER)})
    return df


def group_rollup(df, camp_df, roas_policy=TARGET_ROAS):
    out = []
    order = list(GROUPS.keys()) + [f"{s} (standalone)" for s in STANDALONE]
    for g in order:
        sub = df[df["group"] == g]
        if not len(sub):
            continue
        readable = sub[sub["sub_threshold"] == 0]
        w = wavg(readable if len(readable) else sub, "rpl", "spend")
        target = w / roas_policy if pd.notna(w) else np.nan
        if g.endswith("(standalone)"):
            shell = match_shell(camp_df, STANDALONE[g.split(" ")[0]])
        else:
            shell = match_shell(camp_df, GROUPS[g]["shell_pattern"])
        cur_tcpa = float(shell["current_tcpa"]) if shell is not None and pd.notna(shell["current_tcpa"]) else np.nan
        conv_day = sub["conversions"].sum() / WINDOW_DAYS
        out.append({
            "group": g,
            "tiers": ", ".join(GROUPS[g]["tiers"]) if g in GROUPS else "TIER SIX (own shell)",
            "shell": str(shell["campaign_name"]) if shell is not None else "(?)",
            "n_states": len(sub), "n_sub": int(sub["sub_threshold"].sum()),
            "spend": sub["spend"].sum(), "conv_day": conv_day,
            "wrpl": w, "target_tcpa": target, "current_tcpa": cur_tcpa,
            "move_pct": (target - cur_tcpa) / cur_tcpa if pd.notna(target) and pd.notna(cur_tcpa) and cur_tcpa else np.nan,
            "std_verdict": ("CLEARS" if conv_day >= CONV_PER_DAY_STANDARD
                            else f"WAIVER ({conv_day:.1f}/day)"),
        })
    return pd.DataFrame(out)


def step_plan(cur, target):
    """List of tCPA steps honoring MAX_SINGLE_STEP_PCT per step."""
    if not (pd.notna(cur) and pd.notna(target)) or cur <= 0:
        return []
    steps, x = [], cur
    guard = 0
    while abs(target - x) / x > MAX_SINGLE_STEP_PCT and guard < 6:
        x = x * (1 + MAX_SINGLE_STEP_PCT * np.sign(target - x))
        steps.append(round(x, 2)); guard += 1
    steps.append(round(target, 2))
    # collapse a trailing micro-step
    if len(steps) >= 2 and abs(steps[-1] - steps[-2]) / steps[-2] < 0.03:
        steps = steps[:-2] + [steps[-1]]
    return steps


def build_step_schedule(groups_df, cutover):
    """Per-group ladder events with computed default dates.
    Small batch + first big steps at cutover+QUIET; subsequent steps spaced
    STEP_SPACING_DAYS. Returns rows: group, shell, step_no, tcpa_from, tcpa_to,
    step_pct, date (dt.date or None), kind."""
    try:
        c0 = dt.date.fromisoformat(str(cutover))
    except Exception:
        c0 = None
    d1 = (c0 + dt.timedelta(days=POST_CUTOVER_QUIET_DAYS)) if c0 else None
    rows = []
    for _, g in groups_df.iterrows():
        cur, tgt = g["current_tcpa"], g["target_tcpa"]
        steps = step_plan(cur, tgt)
        prev = cur
        for i, sv in enumerate(steps, 1):
            step_pct = (sv - prev) / prev if prev else float("nan")
            date = (d1 + dt.timedelta(days=STEP_SPACING_DAYS * (i - 1))) if d1 else None
            rows.append({"group": g["group"], "shell": g["shell"], "step_no": i,
                         "n_steps": len(steps), "tcpa_from": prev, "tcpa_to": sv,
                         "step_pct": step_pct, "date": date,
                         "conv_day_base": g["conv_day"]})
            prev = sv
    return rows


def _forecast_for_step(step_pct):
    """(lead_central, lead_low, lead_high, cpc, confidence, note) for one step."""
    E = ELASTICITY
    if abs(step_pct) <= E["small_move_floor"]:
        return (None, None, None, None, "NOT READABLE",
                "Move too small to verify — every tested ~5% event's range spanned zero. "
                "Expect no attributable signal; do not grade.")
    if step_pct > 0:
        conf = ("Tested range" if step_pct <= E["tested_max_step"] + 0.01
                else "ABOVE tested range — treat band as indicative")
        return (step_pct * E["lead_central"], step_pct * E["lead_low"],
                step_pct * E["lead_high"], step_pct * E["cpc_central"], conf,
                "Raise: CPC steps up immediately (+0-5%) and persists — no spike-then-"
                "catch-up. Leads flat days 0-3, first lift days 4-7, second wave days 11-14.")
    # cut
    return (step_pct * E["lead_central"], step_pct * E["lead_high"],
            step_pct * E["lead_low"], step_pct * E["cpc_central"],
            "UNTESTED CUT — linear extrapolation",
            "All study events were raises. Cuts typically shed volume FASTER than raises "
            "add it (auction-threshold asymmetry) and the loss is likely immediate, not "
            "lagged — treat the band as optimistic-to-realistic and do not grade against "
            "the raise timing curve.")


def write_expected_behavior_sheet(wb, groups_df, schedule, styles, cutover):
    ws = wb.create_sheet("Expected Behavior")
    ws["A1"] = "Pre-registered expectations — written BEFORE execution"
    ws["A1"].font = styles["TITLE_FONT"] if "TITLE_FONT" in styles else TITLE
    note_block(ws, "A2",
        (f"Forecasts from the account's own Jun-Aug tCPA raise study (lead elasticity "
         f"planning value {ELASTICITY['lead_central']}x per % of tCPA, band "
         f"{ELASTICITY['lead_low']}-{ELASTICITY['lead_high']}x; applied PER STEP, max tested "
         f"step +15.4%). Membership cutover held separate: ladder starts >= "
         f"{POST_CUTOVER_QUIET_DAYS} days after cutover to set a new same-weekday baseline; "
         f"steps >= {STEP_SPACING_DAYS} days apart. THE EXPECTED SHAPE OF A RAISE: CPC up "
         f"0-5% immediately and persistently, leads FLAT for days 0-3, first lift days 4-7, "
         f"second wave days 11-14, still building at day 14. Higher CPC with flat leads on "
         f"day 2 is the documented expected state, not a warning sign."), "K", 60)

    hdr = ["group / shell", "step", "planned date", "tCPA from", "tCPA to", "step %",
           "expected lead lift", "expected conv/day", "expected CPC", "confidence", "notes"]
    style_header(ws, 4, hdr, [26, 6, 13, 10, 10, 8, 20, 16, 12, 26, 46])
    r = 5
    for row in schedule:
        c_lead, lo, hi, cpc, conf, note = _forecast_for_step(row["step_pct"])
        base = row["conv_day_base"]
        # compound central estimate through prior steps of the same group
        prior = [x for x in schedule if x["group"] == row["group"] and x["step_no"] < row["step_no"]]
        mult = 1.0
        for p in prior:
            pc, *_ = _forecast_for_step(p["step_pct"])
            mult *= (1 + pc) if pc is not None else 1.0
        exp_conv = (base * mult * (1 + c_lead)) if c_lead is not None else None
