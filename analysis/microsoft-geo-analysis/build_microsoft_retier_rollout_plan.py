def exec_label(campaign_name):
    """Plain-language campaign label for the exec workbook."""
    n = str(campaign_name)
    mt = re.search(r"Tier(\d)", n)
    if mt:
        return f"Tier {mt.group(1)} campaign"
    if "CALIFORNIA" in n.upper():
        return "California campaign"
    if "FLORIDA" in n.upper():
        return "Florida campaign"
    return n[:30]


def match_shell(camp_df, pattern):
    for _, r in camp_df.iterrows():
        if re.search(pattern, str(r["campaign_name"]), flags=re.I):
            return r
    return None


